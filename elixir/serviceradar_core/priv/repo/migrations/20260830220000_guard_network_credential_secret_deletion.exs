      function = "sync_#{table}_network_credential_secret_bindings"

      delete_lines =
        Enum.map_join(fields, "\n", fn {field, path} ->
          "PERFORM #{@prefix}.insert_network_credential_secret_bindings('#{owner_kind}', NEW.id, NEW.#{field}, '#{path}');"
        end)

      execute("""
      CREATE OR REPLACE FUNCTION #{@prefix}.#{function}()
      RETURNS trigger LANGUAGE plpgsql AS $$
      BEGIN
        DELETE FROM #{@prefix}.network_credential_secret_bindings
        WHERE owner_kind = '#{owner_kind}'
          AND owner_id = (CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END)::text;
        IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
        #{delete_lines}
        RETURN NEW;
      END;
      $$;
      """)

      execute(
        "DROP TRIGGER IF EXISTS sync_network_credential_secret_bindings ON #{@prefix}.#{table}"
      )

      execute("""
      CREATE TRIGGER sync_network_credential_secret_bindings
      AFTER INSERT OR UPDATE OR DELETE ON #{@prefix}.#{table}
      FOR EACH ROW EXECUTE FUNCTION #{@prefix}.#{function}()
      """)
    end

    execute("""
    CREATE OR REPLACE FUNCTION #{@prefix}.validate_credential_broker_grant_secret_ref_trigger()
    RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN
      PERFORM #{@prefix}.validate_credential_broker_grant_secret_ref(NEW.secret_ref, NEW.secret_id);
      RETURN NEW;
    END;
    $$;
    """)

    execute(
      "DROP TRIGGER IF EXISTS validate_credential_broker_grant_secret_ref ON #{@prefix}.credential_broker_grants"
    )

    execute("""
    CREATE TRIGGER validate_credential_broker_grant_secret_ref
    BEFORE INSERT OR UPDATE ON #{@prefix}.credential_broker_grants
    FOR EACH ROW EXECUTE FUNCTION #{@prefix}.validate_credential_broker_grant_secret_ref_trigger()
    """)

    # Backfill only the fields live application code uses. Each helper raises for a malformed
    # marker, so an unsafe pre-existing record aborts this migration instead of being skipped.
    for statement <- [
          "SELECT #{@prefix}.insert_network_credential_secret_bindings('notification_channel', id, secret_refs, '$.secret_refs') FROM #{@prefix}.notification_channels",
          "SELECT #{@prefix}.insert_network_credential_secret_bindings('producer_schedule', id, credential_refs, '$.credential_refs') FROM #{@prefix}.producer_schedules",
          "SELECT #{@prefix}.insert_network_credential_secret_bindings('producer_schedule', id, params, '$.params') FROM #{@prefix}.producer_schedules",
          "SELECT #{@prefix}.insert_network_credential_secret_bindings('plugin_assignment', id, params, '$.params') FROM #{@prefix}.plugin_assignments",
          "SELECT #{@prefix}.insert_network_credential_secret_bindings('plugin_target_policy', id, params_template, '$.params_template') FROM #{@prefix}.plugin_target_policies",
          "SELECT #{@prefix}.insert_vulnerability_feed_secret_bindings(id, credential_ref) FROM #{@prefix}.vulnerability_feed_definitions"
        ] do
      execute(statement)
    end

    execute("""
    SELECT #{@prefix}.validate_credential_broker_grant_secret_ref(secret_ref, secret_id)
    FROM #{@prefix}.credential_broker_grants;
    """)
  end

