defmodule ServiceRadar.NATS.ManagedCertificateMountedSeedsTest do
  @moduledoc """
  On a chart install the broker is configured with the public keys of the seeds
  mounted into core, so those seeds are the only signing keys it accepts. Core
  must use exactly them, and must say so when the mount is incomplete rather
  than sign with anything else.

  Every key here is generated by the test.
  """
  use ExUnit.Case, async: false

  alias ServiceRadar.NATS.CertificateAuthorizationToken, as: Token
  alias ServiceRadar.NATS.ManagedCertificateConfiguration, as: Configuration

  @moduletag :tmp_dir

  setup %{tmp_dir: dir} do
    previous_dir = Application.get_env(:serviceradar, :nats_callout_seeds_dir)
    previous_account = Application.get_env(:serviceradar, :nats_account_name)
    Application.put_env(:serviceradar, :nats_callout_seeds_dir, dir)
    Application.put_env(:serviceradar, :nats_account_name, "EXAMPLE")

    on_exit(fn ->
      restore(:nats_callout_seeds_dir, previous_dir)
      restore(:nats_account_name, previous_account)
    end)

    keys = %{
      issuer: Token.new_key(:account),
      auth: Token.new_key(:user),
      system: Token.new_key(:user)
    }

    File.write!(Path.join(dir, "nats-callout-issuer.seed"), keys.issuer.seed <> "\n")
    File.write!(Path.join(dir, "nats-callout-auth.seed"), keys.auth.seed <> "\n")
    File.write!(Path.join(dir, "nats-callout-system.seed"), keys.system.seed <> "\n")

    %{dir: dir, keys: keys}
  end

  test "the mounted seeds and their public keys are the credentials", %{keys: keys} do
    assert {:ok, credentials} = Configuration.credentials()

    assert credentials == %{
             auth_mode: "static_mtls",
             account_name: "EXAMPLE",
             issuer_seed: keys.issuer.seed,
             issuer_nkey: keys.issuer.public_key,
             auth_seed: keys.auth.seed,
             auth_nkey: keys.auth.public_key,
             system_seed: keys.system.seed,
             system_nkey: keys.system.public_key
           }

    assert Configuration.public_config(credentials) == %{
             auth_mode: "static_mtls",
             account_name: "EXAMPLE",
             issuer_nkey: keys.issuer.public_key,
             auth_nkey: keys.auth.public_key,
             system_nkey: keys.system.public_key
           }
  end

  test "a missing seed is reported and nothing else is used", %{dir: dir} do
    File.rm!(Path.join(dir, "nats-callout-auth.seed"))

    assert Configuration.credentials() == {:error, :signing_keys_not_provisioned}
  end

  test "an unreadable seed is reported", %{dir: dir} do
    File.write!(Path.join(dir, "nats-callout-system.seed"), "not a seed\n")

    assert Configuration.credentials() == {:error, :signing_keys_not_provisioned}
  end

  test "the deployment account must be configured" do
    Application.put_env(:serviceradar, :nats_account_name, "not a legal name")

    assert Configuration.credentials() == {:error, :nats_account_unconfigured}
  end

  defp restore(key, nil), do: Application.delete_env(:serviceradar, key)
  defp restore(key, value), do: Application.put_env(:serviceradar, key, value)
end
