defmodule ServiceRadar.Inventory.Identity.Mac do
  @moduledoc """
  MAC address normalization, validation and confidence classification.

  All MAC identifier values in the system are atomic, validated 12-hex-char
  strings produced by this module. Multi-value source fields are split;
  malformed values never become identifiers.
  """

  import Bitwise

  @doc """
  Normalize and validate a MAC address field.

  The field may carry multiple delimited values (Armis emits comma-joined
  MAC histories); the first valid MAC is returned. A valid MAC is exactly
  12 hex characters after stripping `:`/`-`/`.` separators. Anything else
  (malformed values, multi-MAC blobs with no valid entry) returns `nil` and
  must never become an identifier.
  """
  @spec normalize_mac(String.t() | nil) :: String.t() | nil
  def normalize_mac(nil), do: nil

  def normalize_mac(mac) when is_binary(mac) do
    mac
    |> normalize_mac_list()
    |> List.first()
  end

  def normalize_mac(_), do: nil

  @mac_value_pattern ~r/^[0-9A-F]{12}$/

  @doc """
  Normalize a raw MAC field into a list of valid atomic MAC values.

  Splits multi-value fields (comma/semicolon/whitespace delimited), strips
  separators, uppercases, validates each entry to exactly 12 hex characters,
  and dedupes preserving order. Invalid entries are dropped.
  """
  @spec normalize_mac_list(String.t() | nil) :: [String.t()]
  def normalize_mac_list(nil), do: []

  def normalize_mac_list(raw) when is_binary(raw) do
    raw
    |> String.split(~r/[,;\s]+/, trim: true)
    |> Enum.map(&normalize_single_mac/1)
    |> Enum.reject(&is_nil/1)
    |> Enum.uniq()
  end

  def normalize_mac_list(_), do: []

  defp normalize_single_mac(value) do
    normalized =
      value
      |> String.trim()
      |> String.upcase()
      |> String.replace(":", "")
      |> String.replace("-", "")
      |> String.replace(".", "")

    if Regex.match?(@mac_value_pattern, normalized), do: normalized
  end

  @doc """
  Check if a MAC address is locally administered (IEEE bit 1 of the first octet).

  Locally-administered MACs are generated by virtualization, Docker, overlay networks,
  etc. and are not globally unique. They should be registered with medium confidence.

  ## Examples

      iex> IdentityReconciler.locally_administered_mac?("0EEA1432D278")
      true

      iex> IdentityReconciler.locally_administered_mac?("0CEA1432D278")
      false

      iex> IdentityReconciler.locally_administered_mac?("F692BF75C722")
      true

      iex> IdentityReconciler.locally_administered_mac?("F492BF75C722")
      false
  """
  @spec locally_administered_mac?(String.t() | nil) :: boolean()
  def locally_administered_mac?(nil), do: false

  def locally_administered_mac?(mac) do
    normalized = normalize_mac(mac)

    case normalized do
      nil ->
        false

      normalized when byte_size(normalized) >= 2 ->
        {first_byte, _} = Integer.parse(String.slice(normalized, 0, 2), 16)
        band(first_byte, 0x02) != 0

      _ ->
        false
    end
  end

  @doc """
  The set of universally-administered (globally-unique, hardware-anchor) MACs
  from a raw MAC field or a list of them.

  Comma/semicolon/whitespace blobs are normalized to atomic 12-hex MACs first
  (`normalize_mac_list/1`), then locally-administered MACs (virtual/Docker/overlay
  NICs — not hardware anchors) are dropped. This is the exact hardware-identity
  unit the ingest-time distinct-MAC veto (`BatchResolver`) resolves on; reuse it
  for detection/grouping so an un-merge cannot drift from prevention.
  """
  @spec universal_macs([String.t()] | String.t() | nil) :: MapSet.t()
  def universal_macs(values) when is_list(values) do
    values
    |> Enum.flat_map(&normalize_mac_list/1)
    |> Enum.reject(&locally_administered_mac?/1)
    |> MapSet.new()
  end

  def universal_macs(value) when is_binary(value), do: universal_macs([value])
  def universal_macs(_), do: MapSet.new()

  @doc """
  True when two universal-MAC sets are both non-empty and disjoint — the
  distinct-hardware condition the ingest-time veto fires on.
  """
  @spec distinct_hardware?(MapSet.t(), MapSet.t()) :: boolean()
  def distinct_hardware?(%MapSet{} = a, %MapSet{} = b) do
    MapSet.size(a) > 0 and MapSet.size(b) > 0 and MapSet.disjoint?(a, b)
  end

  @doc """
  The IEEE locally-administered sibling of a MAC: the same 48-bit station
  with bit 1 of the first octet flipped.

  Returns nil when the input is not a valid MAC. Used as a lookup key so a
  UniFi WAN identity (`F4…`, universally administered) and the SNMP LAN
  identity of the same NIC (`F6…`, locally administered) resolve to one device.
  """
  @spec hardware_mac_sibling(String.t() | nil) :: String.t() | nil
  def hardware_mac_sibling(mac) do
    case normalize_mac(mac) do
      nil ->
        nil

      normalized ->
        {first_byte, _} = Integer.parse(String.slice(normalized, 0, 2), 16)

        flipped =
          first_byte
          |> bxor(0x02)
          |> Integer.to_string(16)
          |> String.pad_leading(2, "0")
          |> String.upcase()

        flipped <> String.slice(normalized, 2, 10)
    end
  end

  @doc """
  True when two MACs are the universal/local pair of the same 48-bit station.

  Ubiquiti (and some other vendors) expose the burned-in NIC MAC and a
  locally-administered variant that differs only by IEEE bit 1 of the first
  octet. Those are one device, not two hosts sharing a recycled address.
  """
  @spec hardware_mac_siblings?(String.t() | nil, String.t() | nil) :: boolean()
  def hardware_mac_siblings?(left, right) do
    left = normalize_mac(left)
    right = normalize_mac(right)

    is_binary(left) and is_binary(right) and hardware_mac_sibling(left) == right
  end

  @spec any_hardware_mac_siblings?([String.t()], [String.t()]) :: boolean()
  def any_hardware_mac_siblings?(lefts, rights) when is_list(lefts) and is_list(rights) do
    Enum.any?(lefts, fn left ->
      Enum.any?(rights, &hardware_mac_siblings?(left, &1))
    end)
  end

  @doc """
  Observed MACs plus each address's hardware sibling, for identifier *lookup*
  only. Siblings must never be registered as if they were observed.
  """
  @spec lookup_macs_with_siblings([String.t()] | String.t() | nil) :: [String.t()]
  def lookup_macs_with_siblings(macs) when is_list(macs) do
    normalized =
      macs
      |> Enum.flat_map(&normalize_mac_list/1)
      |> Enum.uniq()

    siblings =
      normalized
      |> Enum.map(&hardware_mac_sibling/1)
      |> Enum.reject(&is_nil/1)

    Enum.uniq(normalized ++ siblings)
  end

  def lookup_macs_with_siblings(mac) when is_binary(mac), do: lookup_macs_with_siblings([mac])
  def lookup_macs_with_siblings(_), do: []

  @doc """
  Return the appropriate confidence level for a MAC address.
  Locally-administered MACs get :medium, globally-unique MACs get :strong.
  """
  @spec mac_confidence(String.t() | nil) :: :strong | :medium
  def mac_confidence(mac) do
    if locally_administered_mac?(mac), do: :medium, else: :strong
  end
end
